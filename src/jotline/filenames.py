"""Readable note filenames: a title slug, then a short ID.

The note ID is the identity used by links, history, encryption, and recovery.
The filename is only where that note sits on disk. A generated note can be
stored as ``buy-milk--a1b2c3.md``; daily logs, encrypted notes, and files that
were not created with a generated ID keep ``<id>.md``.
"""
from __future__ import annotations

import json
import re
import unicodedata
from typing import Literal, Never

SHORT_ID_MIN = 6
SLUG_MAX = 60
SEPARATOR = "--"

FilenameMode = Literal["keep", "readable", "opaque"]

# Slug uses single hyphens only, so the double hyphen cannot appear inside it.
_READABLE = re.compile(r"\A([a-z0-9]+(?:-[a-z0-9]+)*)--([0-9a-f]{6,32})\.md\Z")
_GENERATED = re.compile(r"\A[0-9a-f]{32}\Z")
_HEADER_START = re.compile(r"\A---\r?\njotline: 1\r?\n")


def is_generated_id(note_id: str) -> bool:
    """True for IDs Jotline mints with uuid4().hex. Anything else keeps its name."""
    return _GENERATED.fullmatch(note_id) is not None


def readable_parts(filename: str) -> tuple[str, str] | None:
    """``(slug, short_id)`` when ``filename`` is a readable note name."""
    match = _READABLE.fullmatch(filename)
    if match is None:
        return None
    return match.group(1), match.group(2)


def slugify(title: str) -> str:
    """ASCII slug. Accents are stripped; a title with no ASCII letters or digits is ``note``."""
    ascii_text = unicodedata.normalize("NFKD", title).encode("ascii", "ignore").decode("ascii")
    slug = re.sub(r"[^a-z0-9]+", "-", ascii_text.casefold()).strip("-")
    if len(slug) > SLUG_MAX:
        cut = slug[:SLUG_MAX]
        trimmed = cut.rsplit("-", 1)[0] if "-" in cut else cut
        slug = (trimmed or cut).strip("-")
    return slug or "note"


def allocate_filename(note_id: str, title: str, occupied: set[str], *, current: str | None = None) -> str:
    """``slug--short.md``, lengthening the ID prefix until the name is free.

    ``current`` is treated as free: renaming a note onto its own name is not a collision.
    When every prefix is taken, return ``current`` if this note already has a file,
    otherwise ``<id>.md``.
    """
    slug = slugify(title)
    length = SHORT_ID_MIN
    while length < len(note_id):
        name = f"{slug}{SEPARATOR}{note_id[:length]}.md"
        if name not in occupied or name == current:
            return name
        length += 2
    name = f"{slug}{SEPARATOR}{note_id}.md"
    if name not in occupied or name == current:
        return name
    return current or f"{note_id}.md"


def filename_for(
    note_id: str,
    title: str,
    *,
    encrypted: bool,
    mode: FilenameMode,
    current: str,
    occupied: set[str],
) -> str:
    """The filename a save or migration should publish for this note.

    Daily logs stay ``daily-YYYY-MM-DD.md`` (the ID already is the filename).
    Encrypted notes stay ``<id>.md`` so the title is not written beside the ciphertext.
    Files whose ID was not generated by Jotline keep ``<id>.md`` too.
    ``keep`` leaves a plaintext generated note where it is. ``readable`` applies the slug.
    ``opaque`` puts a generated note back under ``<id>.md``.
    """
    opaque = f"{note_id}.md"
    if note_id.startswith("daily-") or encrypted or not is_generated_id(note_id):
        return opaque
    match mode:
        case "keep":
            return current
        case "readable":
            return allocate_filename(note_id, title, occupied, current=current)
        case "opaque":
            return opaque
        case unreachable:
            never: Never = unreachable
            raise AssertionError(never)


def header_needs_id(filename: str, note_id: str) -> bool:
    """The file records ``id`` only when its name is not already the note ID."""
    stem = filename[:-3] if filename.endswith(".md") else filename
    return stem != note_id


def set_header_id(raw: str, note_id: str | None) -> str:
    """Add, replace, or remove the ``id`` field. Bytes after the header stay as they are.

    ``note_id`` None removes the field. A file with no Jotline header gains a
    minimal one when an ID is required, and is left untouched when it is not.
    """
    bom = "\ufeff" if raw.startswith("\ufeff") else ""
    body = raw[len(bom):]
    if not _HEADER_START.match(body):
        if note_id is None:
            return raw
        return bom + "---\njotline: 1\nid: " + json.dumps(note_id) + "\n---\n" + body
    boundary = re.search(r"\r?\n---\r?\n", body)
    if boundary is None:
        raise ValueError("Incomplete Jotline metadata header")
    newline = "\r\n" if "\r\n" in body[:boundary.end()] else "\n"
    # The first header line is the version marker, which is written again below.
    header = body[body.index("\n") + 1:boundary.start()]
    kept = [line for line in header.splitlines()
            if not line.startswith("id: ") and not line.startswith("jotline:")]
    if note_id is not None:
        kept.insert(0, "id: " + json.dumps(note_id))
    rebuilt = "---" + newline + "jotline: 1" + newline
    if kept:
        rebuilt += newline.join(kept) + newline
    rebuilt += "---" + newline
    return bom + rebuilt + body[boundary.end():]
